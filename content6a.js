  function lettered(vals, target, o) {
    const sorted = vals.slice().sort(function (a, b) { return F(a).cmp(F(b)); });
    const L = ['A', 'B', 'C', 'D', 'E'];
    const pts = sorted.map(function (x, i) { return { x: x, label: L[i] }; });
    let letter = '';
    sorted.forEach(function (x, i) { if (F(x).eq(F(target))) letter = L[i]; });
    return { vis: line(Object.assign({ points: pts }, o)), letter: letter, letters: L.slice(0, sorted.length) };
  }
