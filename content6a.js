  function pathVis(a, moves) {
    const pts = [a], jumps = [];
    let x = a;
    moves.forEach(function (m) { jumps.push({ from: x, to: x + m, label: (m > 0 ? '+' : MIN) + Math.abs(m) }); x += m; pts.push(x); });
    const lo = Math.min.apply(null, pts) - 1, hi = Math.max.apply(null, pts) + 1;
    return line({ from: Math.min(lo, -1), to: Math.max(hi, 1), unit: hi - lo > 12 ? 1 : 2, jumps: jumps, points: [{ x: a, label: '' }] });
  }
