    const old = Math.random;
    let q, gi;
    Math.random = seeded(seed);
    try {
      gi = (typeof genIndex === 'number' && genIndex >= 0 && genIndex < gens.length) ? genIndex : Math.floor(Math.random() * gens.length);
      q = gens[gi](ctx || {});
    } finally { Math.random = old; }
    q.topic = topicId; q.step = step; q.gi = gi; q.seed = seed;
